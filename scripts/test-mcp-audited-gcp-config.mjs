import assert from 'node:assert/strict';
import fs from 'node:fs';
const deploy=fs.readFileSync('.github/workflows/deploy-cloud-run-mcp.yml','utf8');
const audit=fs.readFileSync('scripts/auditar-classroom-mcp-gcp.sh','utf8');
assert.match(deploy,/projects\/148028894895\/locations\/global\/workloadIdentityPools\/github-classroom-pool\/providers\/github/);
assert.doesNotMatch(deploy,/\$\{\{ vars\.GCP_WIF_PROVIDER \}\}/);
assert.match(deploy,/academic-classroom-mcp-oauth/);
assert.match(deploy,/academic-write-hmac/);
assert.match(deploy,/academic-mcp-allowed-subjects/);
assert.doesNotMatch(deploy,/classroom-mcp-token/);
assert.match(deploy,/MCP_OAUTH_ISSUER/);
assert.match(deploy,/MCP_OAUTH_JWKS_URL/);
assert.match(deploy,/--allow-unauthenticated/);
assert.match(deploy,/--set-secrets/);
assert.match(audit,/gcloud iam service-accounts get-iam-policy/);
assert.match(audit,/gcloud projects get-iam-policy/);
assert.match(audit,/gcloud secrets describe/);
assert.doesNotMatch(audit,/gcloud secrets versions access/);
assert.doesNotMatch(audit,/gcloud secrets create/);
assert.doesNotMatch(audit,/gcloud projects add-iam-policy-binding/);
assert.doesNotMatch(audit,/gcloud run deploy/);
console.log('PASS: audited WIF reuse, distinct OAuth service, separate HMAC and OAuth allowlist names; Cloud Shell remains read-only.');
